import { build } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const result = await build({
  entryPoints: [fileURLToPath(new URL('stage/runtime.mjs', root))],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['safari16', 'chrome120'],
  minify: true,
  write: false,
  plugins: [
    {
      name: 'local-video-decoder',
      setup(builder) {
        builder.onLoad({ filter: /video-media\.mjs$/ }, async ({ path }) => ({
          contents: (await readFile(path, 'utf8')).replace(
            '"/assets/mediabunny-1.60.0.min.mjs"',
            '"mediabunny"',
          ),
          loader: 'js',
        }));
      },
    },
  ],
});
const font = await readFile(new URL('../../../assets/TikTokSans.ttf', import.meta.url));
const html = `<!doctype html><html><head><meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; img-src data: blob:; media-src data: blob:; font-src data:"><style>
@font-face{font-family:'TikTok Sans';src:url(data:font/ttf;base64,${font.toString('base64')});font-weight:100 900}
*{box-sizing:border-box}html,body{margin:0;width:100%;height:100%;overflow:hidden;background:#EDEFE7;touch-action:none;user-select:none}body{display:flex;align-items:center;justify-content:center}#stage{position:relative;flex:none;box-shadow:0 4px 22px #1e241b15}canvas{width:100%;height:100%;display:block}#selection{position:absolute;border:2px solid #5D7C37;pointer-events:none;transform-origin:center}#selection[hidden]{display:none}.handle{position:absolute;width:44px;height:44px;pointer-events:auto;display:flex;align-items:center;justify-content:center}.handle:after{content:'';width:12px;height:12px;background:white;border:2px solid #5D7C37;border-radius:50%}#resize{right:-23px;bottom:-23px}#rotate{left:calc(50% - 22px);top:-42px}#rotate:after{width:14px;height:14px;background:#DCEABF}
</style></head><body><div id="stage"><canvas></canvas><div id="selection" hidden><div class="handle" id="resize" data-handle="resize"></div><div class="handle" id="rotate" data-handle="rotate"></div></div></div><script>${result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script')}</script></body></html>`;
await mkdir(new URL('src/generated/', root), { recursive: true });
await writeFile(
  new URL('src/generated/stage.ts', root),
  `// Generated by npm run mobile:stage.\nexport default ${JSON.stringify(html)};\n`,
);
await writeFile(new URL('stage/preview.generated.html', root), html);
console.log(`Bundled local slide renderer (${Math.round(html.length / 1024)} KB).`);
